"""Download every old-site file linked from the publication and thesis pages:
/images/<digits>/<file> -> public/images/<digits>/<file> (same path), 1 request/second.

Resumable: files are streamed to <file>.part and renamed when complete, so an existing file is
always complete and is skipped. `--verify-size` additionally compares existing files with the
server's Content-Length (one HEAD request each) and re-downloads on mismatch.
"""

from __future__ import annotations

import logging
import re
from urllib.parse import unquote, urljoin, urlsplit

from bs4 import BeautifulSoup

from ..common import PUBLIC_DIR, REPORTS_DIR
from .assets import OLD_ORIGIN, AssetStore
from .fetch import PUBLICATION_PAGES, page_url, read_page
from .links import OLD_HOSTS

log = logging.getLogger("lamor_tools.migrate")

FILE_RE = re.compile(r"^/images/\d+/[^/]+$")


def collect_links(pages: list[str]) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    """[(page, decoded path)] of old-site /images/<n>/<file> links, and [(page, url)] of other old-site file links."""
    files: list[tuple[str, str]] = []
    other: list[tuple[str, str]] = []
    seen: set[str] = set()
    for name in pages:
        base = page_url(name)
        soup = BeautifulSoup(read_page(name), "lxml")
        area = soup.select_one("div#cms_area_middle") or soup
        for a in area.find_all("a", href=True):
            url = urljoin(base, a["href"].strip())
            parts = urlsplit(url)
            if parts.netloc.lower() not in OLD_HOSTS:
                continue
            path = unquote(parts.path)
            if FILE_RE.match(path):
                if path not in seen:
                    seen.add(path)
                    files.append((name, path))
            elif re.search(r"\.(pdf|docx?|pptx?|zip)$", path, re.I):
                other.append((name, url))
    return files, other


def download_pdfs(dry_run: bool = False, verify_size: bool = False) -> AssetStore:
    store = AssetStore()
    files, other = collect_links(PUBLICATION_PAGES + ["thesis"])
    log.info("%d files linked from the publication and thesis pages", len(files))
    resized = []
    for i, (page, path) in enumerate(files, 1):
        dest = PUBLIC_DIR / path.lstrip("/")
        if dry_run:
            print(f"{'exists ' if dest.exists() else 'missing'} {path}")
            continue
        if verify_size and dest.exists():
            resp = store.client().request("HEAD", OLD_ORIGIN + path, allow_redirects=True)
            remote = int(resp.headers.get("Content-Length", "-1"))
            if resp.status_code == 200 and remote >= 0 and remote != dest.stat().st_size:
                log.warning("%s: size %d != remote %d, re-downloading", path, dest.stat().st_size, remote)
                dest.unlink()
                resized.append(path)
        if not dest.exists():
            log.info("[%d/%d] %s", i, len(files), path)
        store.old_site_file(path)
    if not dry_run:
        write_pdf_report(store, files, other, resized)
    return store


def write_pdf_report(store: AssetStore, files, other, resized) -> None:
    total = sum((PUBLIC_DIR / p.lstrip("/")).stat().st_size for _, p in files if (PUBLIC_DIR / p.lstrip("/")).exists())
    present = sum(1 for _, p in files if (PUBLIC_DIR / p.lstrip("/")).exists())
    by_page: dict[str, int] = {}
    for page, _ in files:
        by_page[page] = by_page.get(page, 0) + 1
    lines = [
        "# Publication / thesis file downloads",
        "",
        "Generated by `uv run lamor-migrate pdfs`. Files keep their old path: `/images/<n>/<file>` -> `public/images/<n>/<file>`.",
        "",
        f"- Unique files linked: {len(files)} (" + ", ".join(f"{k}: {v}" for k, v in by_page.items()) + ")",
        f"- Present on disk: {present} ({total:,} bytes in total)",
        f"- Downloaded this run: {len(store.downloaded)} ({store.bytes_downloaded:,} bytes); skipped (already on disk): {len(store.existing)}",
        f"- Failed: {len(store.failed)}",
    ]
    if resized:
        lines += ["", "Re-downloaded because the size differed from the server:"] + [f"- {p}" for p in resized]
    if store.failed:
        lines += ["", "## Failed downloads", ""] + [f"- {u} ({why})" for u, why in store.failed]
    if store.dead:
        lines += ["", "## Dead links", ""] + [f"- {u}" for u in sorted(set(store.dead))]
    if other:
        lines += ["", "## Other old-site file links (not under /images/<n>/, not downloaded)", ""]
        lines += [f"- {page}: {url}" for page, url in other]
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "pdfs.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
