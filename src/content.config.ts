import { defineCollection } from 'astro:content';
import { file, glob } from 'astro/loaders';
import { z } from 'astro/zod';
import { existsSync, readFileSync } from 'node:fs';
import { parse as parseYaml } from 'yaml';

// Every editable item is one Markdown file with YAML frontmatter (works best with Pages CMS).
const markdown = (dir: string) => glob({ pattern: '**/*.md', base: `./src/content/${dir}` });

// Root-relative path inside the site ("/images/x.png") or an absolute URL.
const path = z.string();
const order = z.number().default(100);

const news = defineCollection({
  loader: markdown('news'),
  schema: z.object({
    title: z.string(),
    date: z.coerce.date(),
    updated: z.coerce.date().optional(),
    author: z.string().optional(),
    image: path.optional(),
    imageAlt: z.string().optional(),
    // Short text shown in news lists (Markdown). The Markdown body is the optional full article.
    lead: z.string().default(''),
    attachments: z.array(z.object({ file: path, label: z.string().optional() })).default([]),
    draft: z.boolean().default(false),
  }),
});

const projects = defineCollection({
  loader: markdown('projects'),
  schema: z.object({
    acronym: z.string(),
    title: z.string(),
    status: z.enum(['ongoing', 'past']),
    logo: path.optional(),
    website: z.string().optional(),
    funding: z.string().optional(),
    start: z.coerce.date().optional(),
    end: z.coerce.date().optional(),
    duration: z.string().optional(), // free-text fallback when exact dates are unknown
    pi: z.string().optional(),
    team: z.array(z.string()).default([]),
    partners: z.array(z.string()).default([]),
    sidebar: z.boolean().default(false), // show the logo in the "Current Projects" sidebar box
    order,
  }),
});

const people = defineCollection({
  loader: markdown('people'),
  schema: z.object({
    name: z.string(),
    category: z.enum(['faculty', 'senior', 'phd', 'manager', 'alumni', 'guest', 'intern']),
    role: z.string().optional(),
    group: z.string().optional(),
    photo: path.optional(),
    profile: z.string().optional(),
    email: z.string().optional(),
    affiliation: z.string().optional(),
    croris_id: z.number().optional(),
    order,
  }),
});

const equipment = defineCollection({
  loader: markdown('equipment'),
  schema: z.object({
    name: z.string(),
    kind: z.enum(['robot', 'sensor']),
    image: path.optional(),
    manufacturer: z.string().optional(),
    link: z.string().optional(),
    order,
  }),
});

const partners = defineCollection({
  loader: markdown('partners'),
  schema: z.object({
    name: z.string(),
    country: z.string().optional(),
    logo: path.optional(),
    website: z.string().optional(),
    order,
  }),
});

const courses = defineCollection({
  loader: markdown('courses'),
  schema: z.object({
    name: z.string(),
    name_hr: z.string().optional(),
    level: z.enum(['undergraduate', 'graduate', 'phd']),
    url: z.string().optional(),
    url_hr: z.string().optional(),
    order,
  }),
});

const theses = defineCollection({
  loader: markdown('theses'),
  schema: z.object({
    title: z.string(),
    author: z.string(),
    year: z.number().int(),
    type: z.string().default('Doctoral thesis'),
    supervisors: z.array(z.string()).default([]),
    pdf: path.optional(),
    url: z.string().optional(),
  }),
});

const pages = defineCollection({
  loader: markdown('pages'),
  schema: z.object({
    title: z.string(),
    description: z.string().optional(),
  }),
});

const settings = defineCollection({
  loader: file('src/data/site.yaml', { parser: (text) => ({ site: parseYaml(text) }) }),
  schema: z.object({
    title: z.string(),
    short_title: z.string(),
    description: z.string(),
    email: z.string(),
    phone: z.string().optional(),
    fax: z.string().optional(),
    address: z.array(z.string()),
    map_url: z.string().optional(),
    repo_url: z.string().optional(),
    carousel: z.array(z.object({ src: path, alt: z.string().default('') })).default([]),
    external_sites: z.array(z.object({ label: z.string(), url: z.string(), image: path.optional() })).default([]),
  }),
});

function readOptional(filePath: string): string {
  return existsSync(filePath) ? readFileSync(filePath, 'utf8') : '';
}

// Generated by tools/ (CRORIS sync + export), merged with hand-made additions and corrections.
const publications = defineCollection({
  loader: async () => {
    const generated: Record<string, unknown>[] = JSON.parse(readOptional('src/data/publications.json') || '[]');
    const extra: Record<string, unknown>[] = parseYaml(readOptional('src/data/publications-extra.yaml')) ?? [];
    const overrides: Record<string, unknown>[] = parseYaml(readOptional('src/data/publication-overrides.yaml')) ?? [];
    const byId = new Map(overrides.map((o) => [String(o.id), o]));
    return [...generated, ...extra]
      .map((p) => ({ ...p, ...byId.get(String(p.id)), id: String(p.id) }))
      .filter((p) => !(p as { hide?: boolean }).hide);
  },
  schema: z.object({
    category: z.enum(['journal', 'conference']),
    year: z.number().int(),
    title: z.string(),
    authors: z.array(z.object({ name: z.string(), lab: z.boolean().default(false) })),
    venue: z.string().default(''),
    details: z.string().default(''),
    status: z.string().optional(),
    doi: z.string().optional(),
    url: z.string().optional(),
    croris: z.number().optional(),
    pdf: path.optional(),
  }),
});

export const collections = { news, projects, people, equipment, partners, courses, theses, pages, settings, publications };
